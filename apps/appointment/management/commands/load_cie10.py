class Command(BaseCommand):
    help = 'Carga el catálogo CIE-10 en la base de datos.'

    def add_arguments(self, parser):
        parser.add_argument('--reset', action='store_true', help='Borra todos los códigos antes de cargar.')

    @transaction.atomic
    def handle(self, *args, **options):
        from apps.appointment.models import Cie10Code

        if options['reset']:
            Cie10Code.objects.all().delete()

        existing = set(Cie10Code.objects.values_list('code', flat=True))
        to_create = [
            Cie10Code(code=code, description=desc)
            for code, desc in CIE10_DATA
            if code not in existing
        ]
        if to_create:
            Cie10Code.objects.bulk_create(to_create, ignore_conflicts=True)

        total = Cie10Code.objects.count()
        self.stdout.write(self.style.SUCCESS(f'Listo: {total} códigos CIE-10 en la base de datos.'))
